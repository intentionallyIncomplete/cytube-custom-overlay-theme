function writeBundleEntry(bundle) {
  fs.mkdirSync(entriesDir, { recursive: true });
  const entryPath = path.join(entriesDir, `${bundle.name}.entry.js`);
  const imports = bundle.modules
    .map((modulePath) => {
      const tsPath = modulePath.replace(/\.js$/, ".ts");
      const actualPath = fs.existsSync(path.join(rootDir, tsPath)) ? tsPath : modulePath;
      return `import "../../${actualPath.replace(/\\/g, "/")}";`;
    })
    .join("\n");
  const body = `/*! Quiglytube ${bundle.name} bundle entry — generated by scripts/build.js */\n${imports}\n`;
  fs.writeFileSync(entryPath, body, "utf8");
  return entryPath;
}

async function buildBundle(bundle, esbuildOptions) {
  const missing = bundle.modules.filter((modulePath) => {
    const fullPath = path.join(rootDir, modulePath);
    return !fs.existsSync(fullPath) && !fs.existsSync(fullPath.replace(/\.js$/, ".ts"));
  });
  if (missing.length) {
    console.warn(`⚠ Skipping missing modules in ${bundle.name}: ${missing.join(", ")}`);
  }

  const entryPath = writeBundleEntry(bundle);
  const outfile = path.join(distDir, `${bundle.name}.bundle.js`);
  const result = await esbuild.build({
    ...esbuildOptions,
    entryPoints: [entryPath],
    outfile,
    banner: { js: `/*! Quiglytube ${bundle.name} bundle */\n${MODULE_BUNDLE_BANNER}` }
  });

  if (result.errors.length) {
    throw new Error(`esbuild failed for ${bundle.name}: ${result.errors.map((e) => e.text).join("; ")}`);
  }

  const sizeKb = (fs.statSync(outfile).size / 1024).toFixed(1);
  console.log(`✓ Built ${bundle.name}.bundle.js (${sizeKb}KB)`);
}

async function buildFrameworkLoader(esbuildOptions) {
  const entry = path.join(rootDir, "src", "billtube-fw.ts");
  const outfile = path.join(distDir, "billtube-fw.js");
  await esbuild.build({
    ...esbuildOptions,
    entryPoints: [entry],
    outfile
  });
  const sizeKb = (fs.statSync(outfile).size / 1024).toFixed(1);
  console.log(`✓ Built dist/billtube-fw.js (${sizeKb}KB)`);
}

function debounce(fn, ms) {
  let timer = null;
  return () => {
    clearTimeout(timer);
    timer = setTimeout(() => {
      timer = null;
      fn();
    }, ms);
  };
}

// Windows directory watches often emit a second event after the rebuild has
// already started. Fold that into one follow-up run instead of overlapping.
function coalesce(fn, ms) {
  let timer = null;
  let running = false;
  let again = false;
  const run = () => {
    timer = null;
    running = true;
    try {
      fn();
    } finally {
      running = false;
      if (again) {
        again = false;
        timer = setTimeout(run, ms);
      }
    }
  };
  return () => {
    if (running) {
      again = true;
      return;
    }
    clearTimeout(timer);
    timer = setTimeout(run, ms);
  };
}

function rebuildLogger(label, outfile, onFirstEnd) {
  let seen = false;
  return {
    name: "rebuild-logger",
    setup(build) {
      build.onEnd((result) => {
        const first = !seen;
        seen = true;
        if (result.errors.length) {
          console.error(`✗ ${label} failed`);
          for (const error of result.errors) {
            console.error(error.text || error);
          }
        } else {
          let sizeNote = "";
          try {
            sizeNote = ` (${(fs.statSync(outfile).size / 1024).toFixed(1)}KB)`;
          } catch {
            /* outfile missing after a failed write */
          }
          console.log(`✓ ${label}${sizeNote}`);
        }
        if (first && onFirstEnd) onFirstEnd();
      });
    }
  };
}

async function buildOnce() {
  const isDev = isDevBuild();
  const esbuildOptions = getEsbuildBaseOptions(isDev);
  const modeLabel = isDev ? "development" : "production";

  console.log(`🔨 Building Quiglytube (${modeLabel})...\n`);
  if (buildFlags.css) {
    buildCss();
    console.log("");
  }
  if (buildFlags.js) {
    copyChannelConfig();
    generateUserReleaseNotes();
    console.log("");
    console.log("Bundling modules with esbuild...\n");
    for (const bundle of bundles) {
      await buildBundle(bundle, esbuildOptions);
    }
    console.log("");
    await generateSri();
    console.log("");
    await buildFrameworkLoader(esbuildOptions);
    console.log("\n✨ Build complete!");
    const verify = spawnSync(process.execPath, ["scripts/verify-dist.js"], {
      cwd: rootDir,
      stdio: "inherit"
    });
    if (verify.status !== 0) process.exit(verify.status || 1);
  } else {
    console.log("\n✨ CSS build complete!");
  }
}

async function buildWatch() {
  const esbuildOptions = getEsbuildBaseOptions(true);
  const loaderOptions = getEsbuildBaseOptions(true, { skipLocalSri: true });
  const contexts = [];
  const watchers = [];

  console.log("🔨 Watching Quiglytube (development)...\n");
  console.log("Local dist/ assets skip SRI checks in this loader build.");
  console.log("Leave `npm run serve` running and refresh the browser after a rebuild.\n");

  copyChannelConfig();
  generateUserReleaseNotes();

  if (buildFlags.css) {
    buildCss();
    console.log("");
    const stylesDir = path.join(rootDir, STYLE_SOURCE_DIR);
    const rebuildCss = coalesce(() => {
      try {
        buildCss();
      } catch (err) {
        console.error(`✗ CSS build failed: ${err.message || err}`);
      }
    }, 100);
    watchers.push(fs.watch(stylesDir, { recursive: true }, rebuildCss));
  }

  if (buildFlags.js) {
    const refreshConfig = debounce(() => {
      try {
        copyChannelConfig();
        generateUserReleaseNotes();
      } catch (err) {
        console.error(`✗ Config refresh failed: ${err.message || err}`);
      }
    }, 100);
    watchers.push(fs.watch(configDir, { recursive: true }, refreshConfig));

    let pendingFirstBuilds = bundles.length + 1;
    const noteFirstBuild = () => {
      pendingFirstBuilds -= 1;
      if (pendingFirstBuilds === 0) {
        console.log("\n👀 Watching src/. Ctrl+C to stop.\n");
      }
    };

    for (const bundle of bundles) {
      const entryPath = writeBundleEntry(bundle);
      const outfile = path.join(distDir, `${bundle.name}.bundle.js`);
      const ctx = await esbuild.context({
        ...esbuildOptions,
        entryPoints: [entryPath],
        outfile,
        banner: { js: `/*! Quiglytube ${bundle.name} bundle */\n${MODULE_BUNDLE_BANNER}` },
        plugins: [rebuildLogger(`${bundle.name}.bundle.js`, outfile, noteFirstBuild)]
      });
      contexts.push(ctx);
    }

    const loaderOut = path.join(distDir, "billtube-fw.js");
    const loaderCtx = await esbuild.context({
      ...loaderOptions,
      entryPoints: [path.join(rootDir, "src", "billtube-fw.ts")],
      outfile: loaderOut,
      plugins: [rebuildLogger("dist/billtube-fw.js", loaderOut, noteFirstBuild)]
    });
    contexts.push(loaderCtx);

    await Promise.all(contexts.map((ctx) => ctx.watch()));
  } else {
    console.log("\n👀 Watching src/. Ctrl+C to stop.\n");
  }

  const shutdown = () => {
    for (const watcher of watchers) watcher.close();
    Promise.all(contexts.map((ctx) => ctx.dispose())).finally(() => process.exit(0));
  };
  process.once("SIGINT", shutdown);
  process.once("SIGTERM", shutdown);
}

const run = buildFlags.watch ? buildWatch : buildOnce;
run().catch((err) => {
  console.error(err);
  process.exit(1);
});
