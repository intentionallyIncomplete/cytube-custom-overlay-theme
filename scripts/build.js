function copyChannelConfig() {
  if (!fs.existsSync(channelConfigSrc)) {
    throw new Error(`Missing ${CHANNEL_CONFIG_SOURCE_PATH}`);
  }
  const body = fs.readFileSync(channelConfigSrc, "utf8");
  const sourceCheck = verifyChannelConfigSource(body);
  if (!sourceCheck.ok) {
    throw new Error(sourceCheck.reason);
  }
  const existing = fs.existsSync(channelConfigOut)
    ? fs.readFileSync(channelConfigOut, "utf8")
    : null;
  if (existing === body) {
    return;
  }
  fs.writeFileSync(channelConfigOut, body, "utf8");
  console.log(`✓ Copied ${CHANNEL_CONFIG_ROOT_PATH} from ${CHANNEL_CONFIG_SOURCE_PATH}`);
}

function generateUserReleaseNotes() {
  const src = path.join(configDir, "user-release-notes.json");
  const out = path.join(rootDir, "src", "modules", "user-release-notes.generated.js");
  let data = { releases: [] };
  if (fs.existsSync(src)) {
    try {
      data = JSON.parse(fs.readFileSync(src, "utf8"));
    } catch (err) {
      console.warn(`⚠ Could not parse user-release-notes.json: ${err.message}`);
    }
  } else {
    console.warn("⚠ src/config/user-release-notes.json missing; using empty releases");
  }
  // Assign to globalThis so esbuild keeps the payload (a bare const is tree-shaken).
  const body = `/* Generated by scripts/build.js — do not edit */\nglobalThis.BTFW_USER_RELEASE_NOTES = ${JSON.stringify(data)};\n`;
  const existing = fs.existsSync(out) ? fs.readFileSync(out, "utf8") : null;
  if (existing === body) {
    return;
  }
  fs.writeFileSync(out, body, "utf8");
  console.log("✓ Generated src/modules/user-release-notes.generated.js");
}

